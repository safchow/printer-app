"""Read what a sliced G-code file says about itself: time, material, colours, layers, thumbnail.

Only the comment header and footer are read (the slicers write their settings
there). Everything is for display; nothing here decides what gets printed.
"""

from __future__ import annotations

import base64
import re
from pathlib import Path
from typing import Any

HEAD_BYTES = 512 * 1024
TAIL_BYTES = 256 * 1024

_KEYS = {
    # key in our meta -> comment keys the slicers use (lower case)
    "estimated_time": ("estimated printing time (normal mode)", "estimated printing time", "print_time"),
    "filament_type": ("filament_type",),
    "filament_colour": ("filament_colour", "filament_color", "extruder_colour"),
    "filament_g": ("total filament used [g]", "filament used [g]", "total filament weight [g]"),
    "filament_mm": ("total filament used [mm]", "filament used [mm]"),
    "layer_height": ("layer_height",),
    "layers": ("total layers count", "total layer number", "layer_count"),
    "printer_model": ("printer_model", "printer_settings_id"),
    "slicer": ("generated by",),
}
_DURATION = re.compile(r"(?:(\d+)d)?\s*(?:(\d+)h)?\s*(?:(\d+)m)?\s*(?:(\d+)s)?")
_LINE = re.compile(r"^;\s*([^=:]+?)\s*[=:]\s*(.+?)\s*$")
_THUMB = re.compile(r"^;\s*thumbnail(?:_PNG)? begin (\d+)x(\d+) \d+\s*$", re.I)


def _seconds(text: str) -> float | None:
    text = text.strip()
    if re.fullmatch(r"\d+(\.\d+)?", text):
        return float(text)
    m = _DURATION.fullmatch(text.replace(" ", ""))
    if not m or not any(m.groups()):
        return None
    d, h, mi, s = (int(x or 0) for x in m.groups())
    return float(((d * 24 + h) * 60 + mi) * 60 + s)


def _read_ends(path: Path) -> tuple[str, str]:
    size = path.stat().st_size
    with path.open("rb") as f:
        head = f.read(HEAD_BYTES)
        tail = b""
        if size > HEAD_BYTES:
            f.seek(max(HEAD_BYTES, size - TAIL_BYTES))
            tail = f.read()
    return head.decode("utf-8", "replace"), tail.decode("utf-8", "replace")


def parse(path: Path) -> tuple[dict[str, Any], bytes | None]:
    """Return (meta, largest PNG thumbnail or None)."""
    if path.suffix.lower() != ".gcode":
        return {}, None
    head, tail = _read_ends(path)
    found: dict[str, str] = {}
    thumbs: list[tuple[int, bytes]] = []
    for text in (head, tail):
        lines = text.splitlines()
        i = 0
        while i < len(lines):
            line = lines[i]
            t = _THUMB.match(line)
            if t:
                w, h = int(t.group(1)), int(t.group(2))
                data = []
                i += 1
                while i < len(lines) and not re.match(r"^;\s*thumbnail(?:_PNG)? end", lines[i], re.I):
                    data.append(lines[i].lstrip("; ").strip())
                    i += 1
                try:
                    png = base64.b64decode("".join(data), validate=False)
                    if png.startswith(b"\x89PNG"):
                        thumbs.append((w * h, png))
                except ValueError:
                    pass
            elif line.startswith(";"):
                m = _LINE.match(line)
                if m:
                    key = m.group(1).strip().lower()
                    found.setdefault(key, m.group(2))
            i += 1

    meta: dict[str, Any] = {}
    for ours, theirs in _KEYS.items():
        for k in theirs:
            if k in found:
                meta[ours] = found[k]
                break
    if "estimated_time" in meta:
        meta["estimated_seconds"] = _seconds(meta.pop("estimated_time"))
    for k in ("filament_g", "filament_mm", "layer_height"):
        if k in meta:
            try:
                meta[k] = round(sum(float(x) for x in str(meta[k]).replace(",", ";").split(";") if x.strip()), 2)
            except ValueError:
                meta.pop(k)
    if "layers" in meta:
        try:
            meta["layers"] = int(float(meta["layers"]))
        except ValueError:
            meta.pop("layers")
    for k in ("filament_type", "filament_colour"):
        if k in meta:
            vals = [v.strip() for v in str(meta[k]).replace(",", ";").split(";") if v.strip()]
            meta[k] = list(dict.fromkeys(vals))
    if "slicer" in meta:
        meta["slicer"] = str(meta["slicer"])[:80]
    meta = {k: v for k, v in meta.items() if v not in (None, [], "")}
    thumb = max(thumbs)[1] if thumbs else None
    return meta, thumb
